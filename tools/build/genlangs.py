def lang_code(name):
    if name in ISO1: return ISO1[name]
    if name in ISO3: return ISO3[name]
    raise SystemExit("缺代碼: " + name)

def main():
    entries = []
    used = set()
    for region, names in DATA:
        for nm in names:
            c = lang_code(nm)
            if c in used:
                raise SystemExit("重複代碼: " + c + " (" + nm + ")")
            used.add(c)
            entries.append((region, c, nm))
    total = len(entries)
    out = ["const LANG_DATA={"]
    for region, names in DATA:
        arr = ", ".join("['%s','%s']" % (lang_code(nm), nm) for nm in names)
        out.append("'%s':[%s]," % (region, arr))
    out.append("};")
    js = "\n".join(out)
    with io.open("genlangs.out.js", "w", encoding="utf-8") as f:
        f.write(js)
    print("OK %d 種語言，代碼唯一" % total)

if __name__ == "__main__":
    main()